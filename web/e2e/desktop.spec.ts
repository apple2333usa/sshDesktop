import { expect, test } from '@playwright/test'
import { closeAll, collectErrors, login, openApp } from './helpers'

test.describe.configure({ mode: 'serial' })

test('登录后进入桌面，任务栏和开始菜单可用', async ({ page }) => {
  const errors = collectErrors(page)
  await login(page)
  await expect(page.getByTestId('desktop')).toBeVisible()
  await expect(page.getByTestId('tb-start')).toBeVisible()
  await page.getByTestId('tb-start').click()
  await expect(page.getByTestId('start-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('start-menu')).toBeHidden()
  expect(errors).toEqual([])
})

