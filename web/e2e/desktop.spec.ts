test('资源管理器：新建、编辑、重命名、删除到回收站并还原', async ({ page }) => {
  const errors = collectErrors(page)
  const dir = '/tmp/sd-e2e-' + Date.now()
  await login(page)
  await closeAll(page)
  const win = await openApp(page, 'explorer')
  // 进入 /tmp，新建测试文件夹
  await win.getByTestId('explorer-address-edit').click()
  await win.getByTestId('explorer-address').locator('input').fill('/tmp')
  await page.keyboard.press('Enter')
  await win.getByTestId('explorer-new').click()
  await page.getByText('新建文件夹', { exact: true }).last().click()
  await page.getByTestId('prompt-input').locator('input').fill(dir.slice(5))
  await page.getByTestId('prompt-ok').click()
  await win.getByTestId('file-' + dir.slice(5)).dblclick()
  await expect(win.getByText('此文件夹为空')).toBeVisible()

  // 新建文件并用编辑器写入
  await win.getByTestId('explorer-new').click()
  await page.getByText('新建文件', { exact: true }).last().click()
  await page.getByTestId('prompt-input').locator('input').fill('hello.txt')
  await page.getByTestId('prompt-ok').click()
  await win.getByTestId('file-hello.txt').dblclick()
  const editor = page.getByTestId('window-editor')
  await expect(editor.locator('.cm-content')).toBeVisible()
  await editor.locator('.cm-content').click()
  await page.keyboard.type('hello sshDesktop')
  await page.keyboard.press('Control+s')
  await expect(page.getByText('已保存').first()).toBeVisible()
  await editor.getByTestId('win-close').click()
  await expect(editor).toBeHidden()

  // 重命名
  await win.getByTestId('file-hello.txt').click()
  await page.keyboard.press('F2')
  await page.getByTestId('prompt-input').locator('input').fill('renamed.txt')
  await page.getByTestId('prompt-ok').click()
  await expect(win.getByTestId('file-renamed.txt')).toBeVisible()
  await expect(win.getByTestId('file-renamed.txt')).toContainText('16 B')

  // 删除到回收站
  await win.getByTestId('file-renamed.txt').click()
  await page.keyboard.press('Delete')
  await page.getByTestId('danger-confirm').click()
  await expect(win.getByTestId('file-renamed.txt')).toBeHidden()

  // 在回收站中还原
  await win.getByTestId('nav-trash').click()
  const row = win.locator('tr', { hasText: dir + '/renamed.txt' })
  await expect(row).toBeVisible()
  await row.locator('.n-checkbox').click()
  await win.getByTestId('trash-restore').click()
  await expect(page.getByText(/已还原 1 项/)).toBeVisible()

  // 回到目录确认文件已还原，然后永久删除整个测试目录
  await win.getByTestId('explorer-address-edit').click()
  await win.getByTestId('explorer-address').locator('input').fill(dir)
  await page.keyboard.press('Enter')
  await expect(win.getByTestId('file-renamed.txt')).toBeVisible()
  await page.keyboard.press('Backspace')
  await win.getByTestId('file-' + dir.slice(5)).click()
  await page.keyboard.press('Shift+Delete')
  await expect(page.getByTestId('danger-password')).toBeVisible()
  await page.getByTestId('danger-password').locator('input').fill(process.env.SD_PASS ?? '')
  await page.getByTestId('danger-confirm').click()
  await expect(win.getByTestId('file-' + dir.slice(5))).toBeHidden()
  await closeAll(page)
  expect(errors).toEqual([])
})

test('进程和系统服务列表', async ({ page }) => {
  const errors = collectErrors(page)
  await login(page)
  await closeAll(page)
  const p = await openApp(page, 'processes')
  await expect(p.locator('tbody tr').first()).toBeVisible()
  await p.getByTestId('proc-search').locator('input').fill('sshdesktop')
  await expect(p.locator('tbody tr').first()).toContainText('sshdesktop')
  await closeAll(page)
  const s = await openApp(page, 'services')
  // 容器等没有 systemd 的环境设置 SD_NO_SYSTEMD=1，只检查页面能打开
  if (process.env.SD_NO_SYSTEMD) await expect(s.locator('.n-data-table')).toBeVisible()
  else await expect(s.locator('tbody tr').first()).toBeVisible({ timeout: 20_000 })
  await closeAll(page)
  expect(errors).toEqual([])
})

